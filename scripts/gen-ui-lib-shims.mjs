#!/usr/bin/env node
/**
 * 轻聊 · UI 库 shim 生成器（v2，干净重写）
 * 为 @mantine/core、@mantine/hooks、@mui/material、lodash、date-fns 生成
 * 按需 re-export 的 shim 模块（指向包内具体文件），避免 rollup 解析 barrel 导致 OOM。
 *
 * 用法: node scripts/gen-ui-lib-shims.mjs
 * 产物: src/renderer/shims/gen/*.ts
 */
import fs from 'node:fs'
import path from 'node:path'

const ROOT = process.cwd()
const OUT = path.join(ROOT, 'src/renderer/shims/gen')
fs.mkdirSync(OUT, { recursive: true })

// ---------- 1. 扫描源码导入 ----------
function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.name === 'node_modules' || e.name === 'shims') continue
    const p = path.join(dir, e.name)
    if (e.isDirectory()) walk(p, out)
    else if (/\.(tsx?|jsx?)$/.test(e.name)) out.push(p)
  }
  return out
}

const LIBS = ['@mantine/core', '@mantine/hooks', '@mui/material', 'lodash', 'date-fns']
const named = new Map(LIBS.map((l) => [l, new Set()]))
const fullLibs = new Set()

const reNamed = /import\s+(?:type\s+)?\{([^}]*)\}\s*from\s*['"]([^'"]+)['"]/g
const reNs = /import\s*\*\s*as\s*\w+\s*from\s*['"]([^'"]+)['"]/g

for (const f of walk(path.join(ROOT, 'src'))) {
  const src = fs.readFileSync(f, 'utf8')
  for (const m of src.matchAll(reNamed)) {
    const set = named.get(m[2])
    if (!set) continue
    for (let part of m[1].split(',')) {
      part = part.trim().replace(/^type\s+/, '')
      const name = part.split(/\s+as\s+/)[0].trim()
      if (name) set.add(name)
    }
  }
  for (const m of src.matchAll(reNs)) {
    if (named.has(m[1])) fullLibs.add(m[1])
  }
}
for (const l of LIBS) console.log(`${l}: 具名 ${named.get(l).size}${fullLibs.has(l) ? '（含 namespace 全量）' : ''}`)

// ---------- 2. barrel 解析 ----------
function pkgDir(name) {
  const dir = path.join(ROOT, 'node_modules', name)
  return fs.existsSync(dir) ? fs.realpathSync(dir) : dir
}

function parseBarrel(indexPath) {
  const map = new Map()
  const text = fs.readFileSync(indexPath, 'utf8')
  const barrelDir = path.dirname(indexPath)
  const resolveSpec = (spec) => {
    if (!spec.startsWith('.')) return null
    const base = path.resolve(barrelDir, spec)
    for (const cand of [base, `${base}.mjs`, `${base}.js`, path.join(base, 'index.mjs'), path.join(base, 'index.js')]) {
      try {
        if (fs.statSync(cand).isFile()) return cand
      } catch {}
    }
    return null
  }
  for (const m of text.matchAll(/export\s*\{([^}]*)\}\s*from\s*['"]([^'"]+)['"]/g)) {
    const target = resolveSpec(m[2])
    if (!target) continue
    for (let part of m[1].split(',')) {
      part = part.trim()
      if (!part) continue
      const as = part.match(/^(\S+)(?:\s+as\s+(\S+))?$/)
      if (!as) continue
      const local = as[1].replace(/^type\s+/, '')
      const exported = as[2] || local
      if (!map.has(exported)) map.set(exported, target)
    }
  }
  for (const m of text.matchAll(/export\s*\*\s*from\s*['"]([^'"]+)['"]/g)) {
    const target = resolveSpec(m[1])
    if (!target) continue
    try {
      for (const [k, v] of parseBarrel(target)) if (!map.has(k)) map.set(k, v)
    } catch {}
  }
  return map
}

function emit(file, lines) {
  fs.writeFileSync(file, lines.join('\n') + '\n')
  console.log(`  -> ${path.relative(ROOT, file)} (${lines.length - 1} 行)`)
}

// ---------- 3a. @mantine/core：全量导出 ----------
{
  const dir = pkgDir('@mantine/core')
  const map = parseBarrel(path.join(dir, 'esm/index.mjs'))
  const lines = ['// AUTO-GENERATED by scripts/gen-ui-lib-shims.mjs — 请勿手改']
  const missing = []
  const names = new Set([...named.get('@mantine/core'), ...map.keys()])
  for (const name of names) {
    const t = map.get(name)
    if (!t) {
      missing.push(name)
      continue
    }
    lines.push(`export { ${name} } from '${t}'`)
  }
  const typeSrc = path.join(dir, 'esm/index.mjs')
  for (const name of missing) lines.push(`export type { ${name} } from '${typeSrc}'`)
  emit(path.join(OUT, 'mantine-core.ts'), lines)
}

// ---------- 3b. @mantine/hooks：全量导出 ----------
{
  const dir = pkgDir('@mantine/hooks')
  const map = parseBarrel(path.join(dir, 'esm/index.mjs'))
  const lines = ['// AUTO-GENERATED by scripts/gen-ui-lib-shims.mjs — 请勿手改']
  const missing = []
  const names = new Set([...named.get('@mantine/hooks'), ...map.keys()])
  for (const name of names) {
    const t = map.get(name)
    if (!t) {
      missing.push(name)
      continue
    }
    lines.push(`export { ${name} } from '${t}'`)
  }
  const typeSrc = path.join(dir, 'esm/index.mjs')
  for (const name of missing) lines.push(`export type { ${name} } from '${typeSrc}'`)
  emit(path.join(OUT, 'mantine-hooks.ts'), lines)
}

// ---------- 3c. @mui/material：逐符号 CJS 互操作 ----------
{
  const dir = pkgDir('@mui/material')
  const STYLE_UTILS = new Set([
    'styled', 'createTheme', 'useTheme', 'ThemeProvider', 'ThemeOptions', 'breakpoints',
    'createBreakpoints', 'createSpacing', 'createTransitions', 'duration', 'easing',
    'getContrastRatio', 'getLuminance', 'hexToRgb', 'hslToRgb', 'decomposeColor',
    'recomposeColor', 'rgbToHex', 'alpha', 'emphasize', 'cssContainerQueries',
  ])
  const lines = ['// AUTO-GENERATED by scripts/gen-ui-lib-shims.mjs — 请勿手改']
  const missing = []
  for (const name of named.get('@mui/material')) {
    let target = null
    const cands = [
      path.join(dir, name, 'index.js'),
      path.join(dir, `${name}.js`),
      path.join(dir, 'styles', name, 'index.js'),
      path.join(dir, 'styles', `${name}.js`),
    ]
    target = cands.find((c) => fs.existsSync(c))
    if (!target && STYLE_UTILS.has(name)) target = path.join(dir, 'styles', 'index.js')
    if (!target) {
      missing.push(name)
      continue
    }
    const v = '_' + name.replace(/\W/g, '_')
    lines.push(`import ${v} from '${target}'`)
    lines.push(`export const ${name} = (${v} as any)?.default ?? ${v}`)
  }
  for (const name of missing) lines.push(`export type { ${name} } from '${path.join(dir, 'index.js')}'`)
  emit(path.join(OUT, 'mui-material.ts'), lines)
}

// ---------- 3d. lodash：全量方法（node_modules 内消费者也用具名导入） ----------
{
  const dir = pkgDir('lodash')
  const lines = ['// AUTO-GENERATED by scripts/gen-ui-lib-shims.mjs — 请勿手改']
  const names = new Set(named.get('lodash'))
  const SKIP = new Set(['index', 'lodash', 'core', 'fp', 'lodash.default', 'toInteger', 'apply', 'cloneBuffer'])
  for (const e of fs.readdirSync(dir)) {
    if (!e.endsWith('.js') || e.startsWith('_')) continue
    const base = e.slice(0, -3)
    if (SKIP.has(base) || base.includes('.')) continue
    names.add(base)
  }
  const usedVars = new Set()
  const validIdent = (n) => {
    try {
      new Function('var ' + n)
      return true
    } catch {
      return false
    }
  }
  for (const name of [...names].sort()) {
    const f = path.join(dir, `${name}.js`)
    if (!fs.existsSync(f) || !validIdent(name)) continue
    let v = '_' + name.replace(/\W/g, '_')
    while (usedVars.has(v)) v += '_'
    usedVars.add(v)
    lines.push(`import ${v} from 'lodash/${name}.js'`)
    lines.push(`export const ${name} = (${v} as any)?.default ?? ${v}`)
  }
  emit(path.join(OUT, 'lodash.ts'), lines)
}

// ---------- 3e. date-fns：ESM 逐函数（叶子文件 default 导出；index.js export * 枚举符号名） ----------
{
  const dir = pkgDir('date-fns')
  const lines = ['// AUTO-GENERATED by scripts/gen-ui-lib-shims.mjs — 请勿手改']
  const missing = []
  const names = new Set(named.get('date-fns'))
  const idxPath = path.join(dir, 'index.js')
  if (fs.existsSync(idxPath)) {
    const idxText = fs.readFileSync(idxPath, 'utf8')
    for (const m of idxText.matchAll(/export\s*\*\s*from\s*["']\.\/([^/"']+)\.js["']/g)) {
      names.add(m[1])
    }
  }
  for (const name of names) {
    const f = path.join(dir, `${name}.js`)
    if (!fs.existsSync(f)) {
      missing.push(name)
      continue
    }
    const v = '_' + name.replace(/\W/g, '_')
    lines.push(`import ${v} from '${f}'`)
    lines.push(`export const ${name} = (${v} as any)?.default ?? ${v}`)
  }
  emit(path.join(OUT, 'date-fns.ts'), lines)
}

console.log('shim 生成完成')
